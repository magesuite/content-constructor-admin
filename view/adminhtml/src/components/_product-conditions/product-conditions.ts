import $t from 'mage/translate';

const ROOT_ID: string = '1';
const COMBINE_CONDITION: string = 'Magento\\CatalogWidget\\Model\\Rule\\Condition\\Combine';
const PRODUCT_CONDITION: string = 'Magento\\CatalogWidget\\Model\\Rule\\Condition\\Product';
const LIST_OPERATORS: string[] = ['()', '!()'];
const MULTISELECT_INPUT_TYPE: string = 'multiselect';
const CHILD_ID_PATTERN: RegExp = /^1--(\d+)$/;

interface ConditionRow {
    attribute: string;
    operator: string;
    value: string;
    values: string[];
}

/**
 * Product conditions editor.
 * Edits the conditions of product grids and carousels in the format of the Catalog Products List widget,
 * so conditions written by hand and generated by AI are interchangeable.
 * @type {vuejs.ComponentOption} Vue component object.
 */
const ccProductConditions: vuejs.ComponentOption = {
    template: `<div class="cc-product-conditions">
        <div class="cc-product-conditions__options cc-product-conditions__options--inputs">
            <p class="cc-input__hint cc-product-conditions__hint">${$t('Show only products matching all of these conditions.')}</p>
            <div class="cc-product-conditions__row" v-for="row in rows">
                <select class="cc-input__select cc-product-conditions__attribute" v-model="row.attribute" @change="resetOperator(row)">
                    <option value="">${$t('Select attribute...')}</option>
                    <option v-for="attribute in attributeList" value="{{ attribute.code }}">{{ attribute.label }}</option>
                </select>
                <select class="cc-input__select cc-product-conditions__operator" v-model="row.operator" :disabled="!row.attribute" v-if="!isFixedValue(row)">
                    <option v-for="operator in getOperators(row)" value="{{ operator.value }}">{{ operator.label }}</option>
                </select>
                <select class="cc-input__select cc-product-conditions__value" v-model="row.values" multiple v-if="!isFixedValue(row) && hasOptions(row) && isMultiValue(row)">
                    <option v-for="option in getOptions(row)" value="{{ option.value }}">{{ option.label }}</option>
                </select>
                <select class="cc-input__select cc-product-conditions__value" v-model="row.value" v-if="!isFixedValue(row) && hasOptions(row) && !isMultiValue(row)">
                    <option value="">${$t('Select value...')}</option>
                    <option v-for="option in getOptions(row)" value="{{ option.value }}">{{ option.label }}</option>
                </select>
                <input type="text" class="cc-input__input cc-product-conditions__value" v-model="row.value" placeholder="{{ getPlaceholder(row) }}" :disabled="!row.attribute" v-if="!isFixedValue(row) && !hasOptions(row)">
                <button type="button" class="action-secondary cc-product-conditions__remove" @click="removeRow($index)">${$t('Remove')}</button>
            </div>
            <button type="button" class="action-secondary cc-product-conditions__add" @click="addRow">${$t('Add condition')}</button>
        </div>
    </div>`,
    props: {
        configuration: {
            type: Object,
            default(): Object {
                return {};
            },
        },
        attributes: {
            type: String,
            default: '',
        },
    },
    data(): any {
        const attributeList: any[] = this.attributes !== '' ? JSON.parse(this.attributes) : [];
        const attributesByCode: any = {};

        attributeList.forEach((attribute: any): void => {
            attributesByCode[attribute.code] = attribute;
        });

        return {
            attributeList,
            attributesByCode,
            rows: this.convertToRows(this.configuration.conditions),
        };
    },
    watch: {
        rows: {
            handler(): void {
                this.$set('configuration.conditions', this.convertToTree(this.rows));
            },
            deep: true,
        },
    },
    methods: {
        addRow(): void {
            this.rows.push({ attribute: '', operator: '', value: '', values: [] });
        },
        removeRow(index: number): void {
            this.rows.splice(index, 1);
        },
        resetOperator(row: ConditionRow): void {
            const operators: any[] = this.getOperators(row);

            row.operator = operators.length ? operators[0].value : '';
            row.value = this.isFixedValue(row) ? this.attributesByCode[row.attribute].fixed_value : '';
            row.values = [];
        },
        getOperators(row: ConditionRow): any[] {
            const attribute: any = this.attributesByCode[row.attribute];

            return attribute ? attribute.operators : [];
        },
        getOptions(row: ConditionRow): any[] {
            const attribute: any = this.attributesByCode[row.attribute];

            return attribute ? attribute.options : [];
        },
        hasOptions(row: ConditionRow): boolean {
            return this.getOptions(row).length > 0;
        },
        isFixedValue(row: ConditionRow): boolean {
            const attribute: any = this.attributesByCode[row.attribute];

            return Boolean(attribute) && attribute.fixed_value !== null && attribute.fixed_value !== undefined;
        },
        isListOperator(row: ConditionRow): boolean {
            return LIST_OPERATORS.indexOf(row.operator) !== -1;
        },
        isMultiValue(row: ConditionRow): boolean {
            const attribute: any = this.attributesByCode[row.attribute];

            return this.isListOperator(row) || Boolean(attribute && attribute.input_type === MULTISELECT_INPUT_TYPE);
        },
        getPlaceholder(row: ConditionRow): string {
            const attribute: any = this.attributesByCode[row.attribute];

            if (attribute && attribute.input_type === 'category') {
                return $t('Category IDs, comma-separated');
            }

            return this.isListOperator(row) ? $t('Values, comma-separated') : '';
        },
        getRowOperator(row: ConditionRow): string {
            const operators: any[] = this.getOperators(row);

            return this.isFixedValue(row) && operators.length ? operators[0].value : row.operator;
        },
        getRowValue(row: ConditionRow): string {
            if (this.isFixedValue(row)) {
                return String(this.attributesByCode[row.attribute].fixed_value);
            }

            if (this.hasOptions(row) && this.isMultiValue(row)) {
                return row.values.join(',');
            }

            return String(row.value).trim();
        },
        splitValues(value: string): string[] {
            return value
                .split(',')
                .map((item: string): string => item.trim())
                .filter((item: string): boolean => item !== '');
        },
        convertToRows(conditions: any): ConditionRow[] {
            if (!conditions || typeof conditions !== 'object') {
                return [];
            }

            return Object.keys(conditions)
                .filter((id: string): boolean => CHILD_ID_PATTERN.test(id) && Boolean(conditions[id].attribute))
                .sort((first: string, second: string): number =>
                    Number(first.match(CHILD_ID_PATTERN)[1]) - Number(second.match(CHILD_ID_PATTERN)[1])
                )
                .map((id: string): ConditionRow => {
                    const rawValue: any = conditions[id].value;
                    const value: string = rawValue === null || rawValue === undefined ? '' : String(rawValue);

                    return {
                        attribute: conditions[id].attribute,
                        operator: conditions[id].operator,
                        value,
                        values: this.splitValues(value),
                    };
                });
        },
        convertToTree(rows: ConditionRow[]): any {
            const completeRows: ConditionRow[] = rows.filter(
                (row: ConditionRow): boolean => row.attribute !== '' && row.operator !== '' && this.getRowValue(row) !== ''
            );

            if (!completeRows.length) {
                return [];
            }

            const conditions: any = {
                [ROOT_ID]: { type: COMBINE_CONDITION, aggregator: 'all', value: '1', new_child: '' },
            };

            completeRows.forEach((row: ConditionRow, index: number): void => {
                conditions[`${ROOT_ID}--${index + 1}`] = {
                    type: PRODUCT_CONDITION,
                    attribute: row.attribute,
                    operator: this.getRowOperator(row),
                    value: this.getRowValue(row),
                };
            });

            return conditions;
        },
    },
};

export default ccProductConditions;
